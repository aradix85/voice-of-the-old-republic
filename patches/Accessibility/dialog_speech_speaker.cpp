// Human-speaker classifier. "Human" is shorthand for the real criterion: the
// speaker delivers an intelligible Basic line with full VO, so reading the
// subtitle would talk over a voice the player already understands. That is
// almost always a human appearance, but Mission (Twi'lek) and Juhani
// (Cathar) speak Basic too, so their rows count as human; genuinely alien
// speakers (Zaalbar, the generic Twi'lek crowd) stay non-human.
//
// The engine's RACE enum is too coarse (Twi'leks, Cathar, Echani and
// Mandalorians are all HUMAN), so the classifier works on appearance.2da
// rows, by label prefix at build time (build/dump-2da/Program.cs), packed
// into one bitmask per game: the two tables differ, so a row index only means
// anything against its own game's mask. When uncertain a row is non-human,
// so the line stays spoken; rows a mod adds fall past the mask and stay
// spoken too. Suppressing an alien by mistake would lose the only
// comprehensible channel; missing a human is only an overlap.

// Generated by build/dump-2da/Program.cs — DO NOT hand-edit. To refresh:
//   cd build/dump-2da && dotnet run k1 > k1-mask.txt 2> k1-rows.txt
//   cd build/dump-2da && dotnet run k2 > k2-mask.txt 2> k2-rows.txt
// then paste the constexpr blocks here. K1: 341 human rows of 509.
constexpr int    kHumanAppearanceMaxIdK1     = 508;
constexpr size_t kHumanAppearanceWordCountK1 = 8;
constexpr uint64_t kHumanAppearanceMaskK1[kHumanAppearanceWordCountK1] = {
    0x00001e67deffedf0ULL,
    0xfffffffff8000000ULL,
    0xff3fffffffffffffULL,
    0x0000000fffffffffULL,
    0x181ffffff8800020ULL,
    0x2d9f9ff87ffc3806ULL,
    0x344ff7e3fffffff6ULL,
    0x1ffffff7ffffffc0ULL,
};

// K2: 424 human rows of 671. Classifier notes live in Program.cs IsHumanK2:
// Twilek_* (renamed from Alien_Twilek_*) excluded, Party_NPC_* blanket-human
// after droid/Wookiee exclusions (covers the K1 leftovers reused in
// flashbacks), Darth Nihilus excluded (non-language vocalisations — his
// subtitle is the only channel).
constexpr int    kHumanAppearanceMaxIdK2     = 670;
constexpr size_t kHumanAppearanceWordCountK2 = 11;
constexpr uint64_t kHumanAppearanceMaskK2[kHumanAppearanceWordCountK2] = {
    0x00001e67deffedf0ULL,
    0xfffffffff8000000ULL,
    0xff3fffffffffffffULL,
    0x0000000fffffffffULL,
    0x181ffffff8800020ULL,
    0x2c9f9ff87ffc3806ULL,
    0x144ff7e0fffffff6ULL,
    0x77c1f9fffffc4fd8ULL,
    0x01de45ff91ffff80ULL,
    0xf02e03ff957ffe1cULL,
    0x000000007f810bdeULL,
};

// RACE enum value for droids (see engine_offsets.h kCreatureStatsRaceOffset).
constexpr int kRaceDroid = 5;

// Speakers whose subtitle is the player's only channel although their
// appearance or race says human or droid, matched case-insensitively on
// CSWSObject.tag. KOTOR 1 only; the game gives each placement its own tag.
//
//   - sasha: a child (human row) speaking an invented language with no VO;
//     her subtitle, stage directions included, is her whole sidequest.
//   - vek (Manaan swoop handler): Sith_Male_Twilek, a row shared with
//     Basic-voiced Sith, but he speaks alien Twi'leki.
//   - Komad Fortuna on Tatooine, Kashyyyk and in the Dune Sea: appearance
//     445 (human), voiced in alien Twi'leki.
//   - kor35_tariga and kor35_adrenas (Korriban): genuinely human models,
//     voiced in alien Twi'leki.
constexpr const char* kNeverSuppressTagsK1[] = {
    "sasha",
    "vek",
    "tat17_03komad_01",
    "kas22_xkomad_01",
    "tat18_11komad_01",
    "kor35_tariga",
    "kor35_adrenas",
};

// The mirror image: speakers whose appearance says non-human but who speak
// Basic with full VO, so their subtitle clashes with the voice. The shared
// alien rows can't be flipped without silencing the crowd that wears them.
//
//   - man26_casandra (Manaan): the alien Twi'lek dancer model.
//   - man28_merc (Hrakert Rift): a human on a non-human row.
//   - kor35_yuthura (Korriban): her one-off Twi'lek model.
//   - Griff Vao in his two Anchorhead placements: a Twi'lek, like Mission.
constexpr const char* kAlwaysSuppressTagsK1[] = {
    "man26_casandra",
    "man28_merc",
    "kor35_yuthura",
    "tat17_griff_01",
    "tat17_griff_02",
};

bool IsHumanAppearance(int appearanceType) {
    const uint64_t* mask;
    int             maxId;
    if (acc::game::IsKotor2()) {
        mask  = kHumanAppearanceMaskK2;
        maxId = kHumanAppearanceMaxIdK2;
    } else {
        mask  = kHumanAppearanceMaskK1;
        maxId = kHumanAppearanceMaxIdK1;
    }
    if (appearanceType < 0 || appearanceType > maxId) return false;
    unsigned idx = static_cast<unsigned>(appearanceType);
    return (mask[idx >> 6] >> (idx & 63)) & 1ULL;
}

// KOTOR 2 has no tag entries yet; C++ forbids zero-length arrays, so its
// empty lists are the IsKotor2 short-circuit.
template <size_t N>
bool TagListed(const char* const (&list)[N], const char* tag) {
    if (!tag || !tag[0]) return false;
    if (acc::game::IsKotor2()) return false;
    for (const char* t : list) {
        if (_stricmp(t, tag) == 0) return true;
    }
    return false;
}

// The creature behind a CLIENT object id, or nullptr.
void* ServerObjectFromClientId(uint32_t clientId) {
    if (clientId == 0 || clientId == kInvalidObjectId) return nullptr;
    uint32_t serverId = acc::engine::ClientToServerObjectId(clientId);
    if (serverId == 0 || serverId == kInvalidObjectId) return nullptr;
    return acc::engine::ResolveServerObjectHandle(serverId);
}

// Given a candidate server object, validate it's a creature and fill the
// tag / race / appearance fields. Returns false (leaving out.speaker null)
// if the object is null, isn't a creature, or a read faults.
bool FillSpeakerFromServerObject(void* partner, SpeakerInfo& out) {
    if (!partner) return false;
    __try {
        int kind = acc::engine::GetObjectKind(partner);
        if (kind != static_cast<int>(acc::engine::GameObjectKind::Creature)) {
            return false;
        }

        out.speaker = partner;
        auto* partnerBytes = reinterpret_cast<unsigned char*>(partner);

        acc::engine::ReadCExoString(partner, kObjectTagOffset,
                                    out.tag, sizeof(out.tag));

        // Through the stats: the creature's own inline cache reads 0 even
        // for fully initialised speakers.
        void* stats = *reinterpret_cast<void**>(
            partnerBytes + kCreatureStatsPointerOffset);
        if (stats) {
            auto* sb = reinterpret_cast<unsigned char*>(stats);
            out.raceEnum   = *reinterpret_cast<unsigned short*>(
                sb + kCreatureStatsRaceOffset);
            out.appearance = *reinterpret_cast<unsigned short*>(
                sb + kCreatureStatsAppearanceTypeOffset);
        }
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        out.speaker = nullptr;
        return false;
    }
    return out.speaker != nullptr;
}

// The current dialog line's speaker as a CLIENT object id, off CGuiInGame;
// kInvalidObjectId or 0 when there is none.
uint32_t ReadGuiDialogSpeakerClientId() {
    uint32_t id = kInvalidObjectId;
    acc::engine::TryReadU32(acc::engine::ResolveGuiInGame(),
                            kCGuiInGameDialogSpeakerOffset, &id);
    return id;
}

