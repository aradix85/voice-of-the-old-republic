// Human-appearance speakers, and droids: either Basic VO (HK-47) or beeps
// whose subtitle carries no meaning (T3-M4; the meaning lives in the reply
// choices, which are read separately). The tag lists override per
// character, and never-suppress wins, since keeping speech on is the safe
// direction.
bool IsSuppressibleSpeaker(const SpeakerInfo& info) {
    if (TagListed(kNeverSuppressTagsK1, info.tag)) return false;
    if (TagListed(kAlwaysSuppressTagsK1, info.tag)) return true;
    return IsHumanAppearance(info.appearance) || info.raceEnum == kRaceDroid;
}

bool ResolveDialogSpeaker(SpeakerInfo& out) {
    out = SpeakerInfo{};

    // The GUI's per-line speaker: the only one named in overheard
    // NPC-to-NPC scenes, where the player is no participant.
    if (FillSpeakerFromServerObject(
            ServerObjectFromClientId(ReadGuiDialogSpeakerClientId()), out)) {
        return true;
    }

    // The player's own conversation partner, a server object handle (not a
    // CSWSObject*): right for 1-on-1 dialog, wrong in multi-party scenes.
    void* player = acc::engine::GetPlayerServerCreature();
    if (!player) return false;

    const uint32_t partnerHandle =
        acc::engine::ReadU32Or0(player, kServerObjectDialogOwnerOffset);
    if (partnerHandle == 0 || partnerHandle == kInvalidObjectId) return false;

    void* partner = acc::engine::ResolveServerObjectHandle(partnerHandle);
    return FillSpeakerFromServerObject(partner, out);
}

// A bark names its owner itself (CSWGuiBarkBubble.object_id, a CLIENT id,
// written by SetBark); the dialog speaker chain is empty for barks. No owner
// means system or loudspeaker feedback, which the caller speaks.
bool ResolveBarkSpeaker(void* barkPanel, SpeakerInfo& out) {
    out = SpeakerInfo{};
    if (!barkPanel) return false;

    uint32_t clientId = 0;
    if (!acc::engine::TryReadU32(barkPanel, kBarkBubbleObjectIdOffset, &clientId)) {
        return false;
    }
    return FillSpeakerFromServerObject(ServerObjectFromClientId(clientId), out);
}

